package com.example.collegeclientandroid.help

/**
 * Модули справки для экранов мобильного клиента ИС «Колледж-Клиент».
 */
enum class InfoSystemHelpModule {
    LOGIN,
    REGISTRATION,
    EMAIL_VERIFICATION,
    HOME_SCHEDULE,
    PROFILE,
    BYPASS_SHEET,
    STUDY_PLAN
}

object InfoSystemHelpTexts {
    fun title(module: InfoSystemHelpModule): String = when (module) {
        InfoSystemHelpModule.LOGIN -> "Вход в систему"
        InfoSystemHelpModule.REGISTRATION -> "Регистрация"
        InfoSystemHelpModule.EMAIL_VERIFICATION -> "Подтверждение e-mail"
        InfoSystemHelpModule.HOME_SCHEDULE -> "Расписание и замены"
        InfoSystemHelpModule.PROFILE -> "Профиль"
        InfoSystemHelpModule.BYPASS_SHEET -> "Обходной лист"
        InfoSystemHelpModule.STUDY_PLAN -> "Учебный план"
    }

    fun paragraphs(module: InfoSystemHelpModule): List<String> = when (module) {
        InfoSystemHelpModule.LOGIN -> listOf(
            "На этом экране выполняется вход уже зарегистрированного пользователя.",
            "Укажите адрес электронной почты и пароль, заданные при регистрации. После нажатия «Войти» приложение обратится к серверу колледжа; при успешной проверке данных откроется экран с расписанием.",
            "Если отображается сообщение об ошибке, проверьте раскладку клавиатуры, корректность e-mail и пароля, а также доступность интернета и адреса сервера в настройках приложения.",
            "Если учётной записи ещё нет, перейдите по ссылке «Нет аккаунта? Зарегистрируйтесь»."
        )
        InfoSystemHelpModule.REGISTRATION -> listOf(
            "Регистрация создаёт новую учётную запись студента в информационной системе.",
            "Заполните поля: ФИО, группа (как в колледже), e-mail и пароль. Нажмите «Отправить код» — на указанный адрес будет отправлено письмо с кодом подтверждения (если регистрация разрешена администратором и сервер доступен).",
            "Пароль хранится на сервере в защищённом виде; не передавайте свои данные третьим лицам.",
            "Если сервер сообщает, что регистрация отключена, обратитесь в учебную часть или к администратору системы."
        )
        InfoSystemHelpModule.EMAIL_VERIFICATION -> listOf(
            "После отправки формы регистрации необходимо подтвердить владение адресом e-mail.",
            "Введите код из письма в поле «Код подтверждения» и нажмите «Подтвердить email». Код имеет ограниченный срок действия; по истечении времени запросите новый код кнопкой «Отправить код повторно» (когда истечёт таймер).",
            "Кнопка «Назад» возвращает к редактированию данных регистрации без завершения подтверждения.",
            "При ошибках проверьте правильность кода и соединение с сервером."
        )
        InfoSystemHelpModule.HOME_SCHEDULE -> listOf(
            "Это основной модуль просмотра расписания занятий и замен на выбранную дату для указанной группы.",
            "Введите номер группы, выберите дату (поле «Дата») и нажмите «Найти расписание». Ниже отобразятся пары на этот день; при наличии замен выводится отдельный блок «Замены».",
            "Кнопка «Обходной лист» открывает локальный список заданий (данные хранятся только на устройстве).",
            "Кнопка «Учебный план группы» открывает учебный план для группы, указанной в поле «Группа» (сначала введите группу).",
            "Кнопка «Профиль» ведёт к данным учётной записи и фотографии студенческого билета.",
            "Строка с информацией о неделе (если показана) помогает ориентироваться в учебном календаре.",
            "Уведомления о важных событиях (например, изменениях) могут приходить через push-службу, если разрешены на устройстве."
        )
        InfoSystemHelpModule.PROFILE -> listOf(
            "В профиле отображаются ФИО, группа и e-mail из учётной записи (поля только для чтения).",
            "Блок «Студенческий билет» предназначен для фотографии: нажмите «Загрузить фото», выберите изображение с устройства — файл отправится на сервер и будет показан в карточке.",
            "Нажмите на фото для просмотра в полноэкранном режиме (масштаб и поворот жестами; иконка со стрелками сбрасывает вид).",
            "«Назад» возвращает к расписанию; «Выйти из системы» завершает сеанс и открывает экран входа."
        )
        InfoSystemHelpModule.BYPASS_SHEET -> listOf(
            "Обходной лист — персональный чек-лист заданий студента. Все пункты и комментарии сохраняются только на этом телефоне и не синхронизируются с сервером колледжа.",
            "Введите текст нового задания и нажмите «Добавить». Отметьте выполнение флажком, при необходимости допишите комментарий к строке. Иконка корзины удаляет задание.",
            "Используйте список для фиксации поручений преподавателей, справок и других шагов обходного листа."
        )
        InfoSystemHelpModule.STUDY_PLAN -> listOf(
            "Здесь показывается учебный план группы, переданный сервером (источник данных настраивается администратором).",
            "Группа подставляется из экрана расписания при переходе по кнопке «Учебный план группы».",
            "При загрузке отображается индикатор ожидания; при ошибке — текст сообщения (проверьте сеть и доступность документа на сервере).",
            "«Назад» возвращает к предыдущему экрану."
        )
    }
}
